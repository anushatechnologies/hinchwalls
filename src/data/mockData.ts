export const interiorApi = {
  /** GET /api/products?category=interior — all interior products */
  getAll: async () => {
    await new Promise(r => setTimeout(r, 300));
    return interiorProducts;
  },

  /** GET /api/products?category=interior&room={room} — filter by room */
  getByRoom: async (room: string) => {
    await new Promise(r => setTimeout(r, 250));
    if (!room || room === 'all') return interiorProducts;
    return interiorProducts.filter(p => p.room?.includes(room) || p.subcategory === room);
  },

  /** GET /api/products/{slug} — interior product detail */
  getBySlug: async (slug: string) => {
    await new Promise(r => setTimeout(r, 200));
    return interiorProducts.find(p => p.slug === slug) || null;
  },

  /** GET /api/products?category=interior&featured=true */
  getFeatured: async (limit = 4) => {
    await new Promise(r => setTimeout(r, 300));
    return interiorProducts.filter(p => p.featured).slice(0, limit);
  },

  /** GET /api/products?category=interior&isBestSeller=true */
  getBestSellers: async (limit = 4) => {
    await new Promise(r => setTimeout(r, 300));
    return interiorProducts.filter(p => p.isBestSeller).slice(0, limit);
  },

  /** GET /api/products?category=interior&isNew=true */
  getNewArrivals: async (limit = 4) => {
    await new Promise(r => setTimeout(r, 300));
    return interiorProducts.filter(p => p.isNew).slice(0, limit);
  },

  /** GET /api/interior/rooms — list all interior rooms */
  getRooms: async () => {
    await new Promise(r => setTimeout(r, 150));
    return interiorRooms;
  },

  /** GET /api/products?category=interior&subcategory={room}&sort={sort}&page={page}&limit={limit} */
  getFiltered: async (params: { room?: string; sort?: string; minPrice?: number; maxPrice?: number; page?: number; limit?: number }) => {
    await new Promise(r => setTimeout(r, 350));
    let result = [...interiorProducts];
    if (params.room && params.room !== 'all') {
      result = result.filter(p => p.room?.includes(params.room!) || p.subcategory === params.room);
    }
    if (params.minPrice !== undefined) result = result.filter(p => p.price >= params.minPrice!);
    if (params.maxPrice !== undefined) result = result.filter(p => p.price <= params.maxPrice!);
    const sort = params.sort || 'featured';
    if (sort === 'price-asc') result.sort((a, b) => a.price - b.price);
    else if (sort === 'price-desc') result.sort((a, b) => b.price - a.price);
    else if (sort === 'rating') result.sort((a, b) => b.rating - a.rating);
    else if (sort === 'newest') result.sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime());
    else result.sort((a, b) => (b.featured ? 1 : 0) - (a.featured ? 1 : 0));
    const page = params.page || 1;
    const limit = params.limit || 12;
    const total = result.length;
    return { products: result.slice((page - 1) * limit, page * limit), total, page, totalPages: Math.ceil(total / limit) };
  },
};

